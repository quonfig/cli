#!/usr/bin/env node
// Vendors the Quonfig agent skill (github.com/quonfig/skills) into the cli
// build as a generated TypeScript module, so `qfg agent install-skill` writes
// the exact same files as `claude plugin install quonfig@quonfig` — with no
// runtime fetch and no new dependency.
//
// Source: $QUONFIG_SKILLS_DIR, else a sibling checkout at ../skills (the
// monorepo layout). Output: src/agent/skill-bundle.generated.ts (checked in).
//
//   node scripts/sync-agent-skill.mjs          # regenerate
//   node scripts/sync-agent-skill.mjs --check  # exit 1 if the checked-in copy drifted
import {existsSync, readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs'
import {dirname, join, relative, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(root, 'src/agent/skill-bundle.generated.ts')
const SKILL_NAME = 'quonfig'

export function skillsRepoDir() {
  return resolve(process.env.QUONFIG_SKILLS_DIR ?? resolve(root, '..', 'skills'))
}

function walk(dir) {
  const out = []
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith('.')) continue
    const full = join(dir, name)
    if (statSync(full).isDirectory()) out.push(...walk(full))
    else out.push(full)
  }

  return out
}

export function render(repoDir) {
  const pluginDir = join(repoDir, 'plugins', SKILL_NAME)
  const skillDir = join(pluginDir, 'skills', SKILL_NAME)
  const plugin = JSON.parse(readFileSync(join(pluginDir, '.claude-plugin', 'plugin.json'), 'utf8'))
  const files = walk(skillDir).map((full) => ({
    content: readFileSync(full, 'utf8'),
    path: relative(skillDir, full).split('\\').join('/'),
  }))

  const body = files
    .map((f) => `  {path: ${JSON.stringify(f.path)}, content: ${JSON.stringify(f.content)}},`)
    .join('\n')

  return `// GENERATED by scripts/sync-agent-skill.mjs from github.com/quonfig/skills
// (plugins/${SKILL_NAME}/skills/${SKILL_NAME}). Do not edit by hand: change the skills repo,
// then run \`node scripts/sync-agent-skill.mjs\`.
/* eslint-disable */
export const SKILL_NAME = ${JSON.stringify(SKILL_NAME)}
export const SKILL_VERSION = ${JSON.stringify(plugin.version)}
export const SKILL_FILES: ReadonlyArray<{path: string; content: string}> = [
${body}
]
`
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const repoDir = skillsRepoDir()
  if (!existsSync(join(repoDir, 'plugins', SKILL_NAME))) {
    console.error(
      `skills repo not found at ${repoDir} (set QUONFIG_SKILLS_DIR or clone github.com/quonfig/skills next to cli/)`,
    )
    process.exit(2)
  }

  const next = render(repoDir)
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    if (current !== next) {
      console.error(`${relative(root, OUT)} is out of date with ${repoDir}. Run: node scripts/sync-agent-skill.mjs`)
      process.exit(1)
    }

    console.log(`${relative(root, OUT)} matches ${repoDir}`)
  } else {
    writeFileSync(OUT, next)
    console.log(`wrote ${relative(root, OUT)} from ${repoDir}`)
  }
}
